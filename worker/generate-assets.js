/**
 * generate-assets.js
 * Reads the built frontend from ../frontend/dist and writes src/assets.js
 * as a JS module mapping URL paths to file contents (text), so the worker
 * can serve the SPA without needing an assets binding.
 *
 * Usage: node generate-assets.js
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const distDir = path.resolve(__dirname, '../frontend/dist');
const outFile = path.resolve(__dirname, 'src/assets.js');

if (!fs.existsSync(distDir)) {
  console.error('ERROR: frontend/dist not found. Build the frontend first:');
  console.error('  cd ../frontend && npm run build');
  process.exit(1);
}

/** Binary file extensions that get base64-encoded. */
const BINARY_EXT = new Set(['.png', '.jpg', '.jpeg', '.gif', '.webp', '.ico', '.woff', '.woff2', '.ttf', '.eot', '.otf', '.mp4', '.webm']);

/** Vite copies public/* to dist root. We map both /favicon.svg and /favicon.svg/ (dir index) if present. */
function collect(dir, prefix, out) {
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const full = path.join(dir, entry.name);
    const rel = path.posix.join(prefix, entry.name);
    if (entry.isDirectory()) {
      // Also register index fallback for directories (e.g. /assets/ -> /assets/index.html rarely used)
      const indexCandidate = path.join(full, 'index.html');
      if (fs.existsSync(indexCandidate)) {
        const content = fs.readFileSync(indexCandidate, 'utf8');
        out['/' + rel + '/'] = { text: content, b64: false };
      }
      collect(full, rel, out);
    } else if (entry.isFile()) {
      const ext = path.extname(entry.name).toLowerCase();
      const key = '/' + rel;
      if (BINARY_EXT.has(ext)) {
        out[key] = { text: fs.readFileSync(full).toString('base64'), b64: true };
      } else if (ext === '.html' && key === '/index.html') {
        out[key] = { text: fs.readFileSync(full, 'utf8'), b64: false };
      } else if (!ext || ext === '.html' || ext === '.js' || ext === '.css' || ext === '.json' || ext === '.svg' || ext === '.txt' || ext === '.map' || ext === '.webmanifest' || ext === '.md') {
        out[key === '/index.html' ? key : key] = { text: fs.readFileSync(full, 'utf8'), b64: false };
      }
    }
  }
}

const assets = {};
collect(distDir, '', assets);

// Ensure root fallback: map "/" to index.html
if (assets['/index.html']) {
  assets['/'] = assets['/index.html'];
}

// Guard: index.html must exist
if (!assets['/index.html']) {
  console.error('ERROR: dist/index.html not found. Did the frontend build complete?');
  process.exit(1);
}

let out = '// AUTO-GENERATED by generate-assets.js - do not edit\n';
out += '// Maps URL paths to static asset contents from the built frontend.\n';
out += 'export const assets = {\n';
const keys = Object.keys(assets);
for (const key of keys) {
  const a = assets[key];
  const safeKey = key.replace(/\\/g, '\\\\').replace(/"/g, '\\"');
  if (a.b64) {
    out += `  "${safeKey}": { b64: true, content: "${a.text}" },\n`;
  } else {
    // Escape for JS string literal
    const content = a.text.replace(/\\/g, '\\\\').replace(/"/g, '\\"').replace(/\r/g, '').replace(/\n/g, '\\n');
    out += `  "${safeKey}": { b64: false, content: "${content}" },\n`;
  }
}
out += '};\n';

fs.writeFileSync(outFile, out, 'utf8');
const kb = Math.round(fs.statSync(outFile).size / 1024);
console.log(`Generated ${outFile} (${keys.length} assets, ${kb} KB)`);